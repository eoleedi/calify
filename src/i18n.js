export function translate(locale, key, variables = {}) {
  const value = messages[locale]?.[key];
  if (value === undefined) throw new Error(`Missing translation: ${locale}.${key}`);
  return value.replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}
